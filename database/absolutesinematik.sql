CREATE DATABASE IF NOT EXISTS absolutesinematik
    CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE absolutesinematik;

SET NAMES utf8mb4;
SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS login_history;
DROP TABLE IF EXISTS title_genres;
DROP TABLE IF EXISTS titles;
DROP TABLE IF EXISTS genres;
DROP TABLE IF EXISTS users;

SET FOREIGN_KEY_CHECKS = 1;

-- ---------------------------------------------------------------------
--  Users
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
    name          VARCHAR(80)  NOT NULL,
    email         VARCHAR(190) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          ENUM('user', 'admin') NOT NULL DEFAULT 'user',
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at DATETIME NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_users_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
--  Login / register history (email + hashed password of every attempt)
-- ---------------------------------------------------------------------
CREATE TABLE login_history (
    id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id       INT UNSIGNED NULL,
    email         VARCHAR(190) NOT NULL,
    action        ENUM('login', 'register', 'logout') NOT NULL,
    status        ENUM('success', 'failed') NOT NULL,
    password_hash VARCHAR(255) NULL,
    ip_address    VARCHAR(45)  NULL,
    user_agent    VARCHAR(255) NULL,
    created_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_history_user (user_id),
    KEY idx_history_email (email),
    CONSTRAINT fk_history_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
--  Genres
-- ---------------------------------------------------------------------
CREATE TABLE genres (
    id   INT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(40)  NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_genres_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
--  Titles (movies and series)
-- ---------------------------------------------------------------------
CREATE TABLE titles (
    id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    type        ENUM('movie', 'series') NOT NULL,
    title       VARCHAR(160) NOT NULL,
    year        SMALLINT UNSIGNED NOT NULL,
    runtime_min SMALLINT UNSIGNED NULL,
    seasons     TINYINT UNSIGNED NULL,
    rating      DECIMAL(3,1) NOT NULL DEFAULT 0.0,
    synopsis    TEXT NOT NULL,
    poster_url  VARCHAR(500) NULL,
    trailer_url VARCHAR(500) NULL,
    video_url   VARCHAR(500) NULL,
    popularity  INT NOT NULL DEFAULT 0,
    is_featured TINYINT(1) NOT NULL DEFAULT 0,
    is_premiere TINYINT(1) NOT NULL DEFAULT 0,
    added_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_titles_type (type),
    KEY idx_titles_year (year),
    KEY idx_titles_popularity (popularity),
    KEY idx_titles_added (added_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ---------------------------------------------------------------------
--  Titles <-> genres
-- ---------------------------------------------------------------------
CREATE TABLE title_genres (
    title_id INT UNSIGNED NOT NULL,
    genre_id INT UNSIGNED NOT NULL,
    PRIMARY KEY (title_id, genre_id),
    KEY idx_tg_genre (genre_id),
    CONSTRAINT fk_tg_title FOREIGN KEY (title_id) REFERENCES titles (id) ON DELETE CASCADE,
    CONSTRAINT fk_tg_genre FOREIGN KEY (genre_id) REFERENCES genres (id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

